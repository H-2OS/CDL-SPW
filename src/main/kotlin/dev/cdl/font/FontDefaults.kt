package dev.cdl.font

/**
 * 出厂默认字体族的**族名**。即设置项 `main_lyric.font.family` 的出厂默认值。
 *
 * ## 2026-09-22：这里曾经是 `MiSans`，现已改回**本机字体**
 *
 * 用户原话：
 *
 * > 「**取消自带字体包，调用自带字体包的路线转到在本机选择的字体上**」
 *
 * 在此之前，插件随包分发 10 个 MiSans TTF（`src/main/resources/fonts/`，约 9.4 MB），
 * 出厂默认值就是其中那一款 `MiSans`。**该路线已整体取消**，理由有两条，
 * 且**第一条是决定性的**：
 *
 * 1. **许可**。MiSans 的《MiSans 字体知识产权许可协议》第 3 条禁止分发字体副本，
 *    第 2 条**明文禁止改编/二次开发**（含禁子集化、禁改字重、禁转格式）——
 *    而「原样把 `.ttf` 打进插件包」落在许可的哪一侧**文本无唯一解**
 *    （详见 `THIRD_PARTY_NOTICES.md` C7 与 §9.2，此前一直记为**未决**）。
 *    取消随包分发后，**这条未决项连同它的风险一并消失**。
 * 2. **体积**。9.4 MB 的包体对一个歌词插件不成比例，而收益只是"用户不必自己装字体"。
 *
 * ## 为什么默认值取 `Microsoft YaHei UI`
 *
 * 判据是**"任何 Windows 上都存在、且中文覆盖完整"**，逐条：
 *
 * - **Win10 / Win11 稳定存在**：它来自系统自带的 `msyh.ttc`（微软雅黑），
 *   不是可选项、不需要用户安装。这一点比"好看"重要得多 ——
 *   默认值一旦指向本机没有的族名，`Font(family, …)` 会**静默退化成 `Dialog`**，
 *   用户看到的是"设了字体但没生效"，且**没有任何报错**（见 [FontLoader] 的同类说明）。
 * - **中文覆盖完整**：歌词以中日文为主，拉丁字体没有汉字会被 AWT 逐字回退，
 *   得到"中英两种字重/字面"的混杂观感。雅黑是简体中文的主力字体。
 * - **与原实现一致**：原实现 SPW 的 `font_family` 默认值**本来就是** `Microsoft YaHei UI`
 *   （`preference_config.json` 的 `default_value` 与 `HostSettings.kt` 的
 *   `config.get("font_family", "Microsoft YaHei UI")` 两处一致）。
 *   本项目「原实现设置面锚定」的取向要求默认值不要无故偏离原实现 ——
 *   2026-09-19 改成 `MiSans` 是为了随包字体这条**现已取消**的路线，故改回。
 * - **和「微软雅黑」的关系**：`msyh.ttc` 内含三个族名 ——
 *   `Microsoft YaHei` / `Microsoft YaHei UI` / `微软雅黑`。
 *   三者**不是同一款**：`…UI` 一档字面更紧凑、行高更小，是 Windows 自己给界面用的那一档。
 *   本项目取 `…UI`，与原实现同款。
 *
 * ## ⚠️★★ 它的语义已在 2026-09-29 变了 —— 它是**回退族**，**不再是**出厂默认值

 * | 时点 | 出厂默认值（`SettingRegistry` 的 `default`） | 本常量 |
 * |---|---|---|
 * | 2026-09-22 ~ 09-29 | `Microsoft YaHei UI` | ★ **同一个东西** |
 * | **2026-09-29 起** | **`@host:MiSans`（哨兵）** | ★★ **回退族**（两者**不再相同**） |
 *
 * ★★ **原记**（本段旧文，2026-10-07 更正）：「它**必须**与 `SettingRegistry` 的 `default`
 * **逐字相同**……故由探针 `FontDefaultProbe` 做机械比对」——
 * ★ **实为**：那条「逐字相同」的比对在 2026-09-29 已被 `FontDefaultProbe` ①
 * **放宽**为「等于本常量 **或** `@host:` 哨兵」⇒ ★ **「机械比对」这条申报已不成立**。
 * ★ 旧文的另一半（「写错的表现是默认字体静默退化成 `Dialog`」）也**只对了一半**：
 * 真正的退化发生在**哨兵解析失败**那一侧，而当时的回退写的是 `Font(哨兵, …)` ——
 * ★★ **本常量那时根本没被当过回退**（见下）。
 *
 * ## ★★★ 它现在的真实职责：**哨兵 / 空值解析失败时的回退族**
 *
 * 由 `font/FontResolution.resolveFontOrFallback`（**唯一漏斗**）消费 ——
 * 渲染层（`render/LetterSpacing`）· 预览（`settingsui/IslandPreviewPane`）·
 * 工具窗（`settingsui/ToolWindowTheme`）三处**共用同一个函数**。
 * ★ 详见 `migration/97-护栏与生产路径错位-2026-10-07.md` 与 **BUG-161**。
 * ★ 探针 `FontDefaultProbe` ②③ 仍断言「它在**本机确实可解析**」——
 * 那正是「回退能成立」的**前提**，故那两条断言仍然有价值（只是**职责变了**）。
 *
 * ## ⚠️ 「开箱观感不再统一」—— 这条如实记下，不要当成没发生
 *
 * 随包字体的原始理由正是"**用户不必自己装字体、开箱就有同一套观感**"。
 * 取消之后，**不同用户的默认观感会不同**：装过字体/改过系统默认的用户，
 * 看到的字面、字重、行高都可能与本机不同。
 * 这是**取消随包字体必然的代价**，不是缺陷；但它意味着
 * 「同一版插件在任何机器上画出来的字完全一致」这句话**从今天起不再成立** ——
 * 凡引用该结论的注释/文档都必须同步改掉（本文件即其中一处）。
 */
