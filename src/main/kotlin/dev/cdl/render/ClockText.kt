// ★★ 为什么"时间源必须可注入"（这是本文件存在的第一理由）
// ══════════════════════════════════════════════════════════════════════════════
//
// 台账 `migration/80` §4 第 1 件逐字：
//
// > **时间源 + 可注入接缝** —— 必须能在探针里注入"假时钟"，
// > 否则断言只能测"现在几点"= **恒绿的空护栏**（§H H1：时间留可注入接缝）。
//
// ★ 所以本文件的每个函数**只吃 `epochMs`**，**绝不内部调 `System.currentTimeMillis()`**。
//   "现在几点"这个**副作用**留在**调用方**（真机 = `System.currentTimeMillis()`，
//   探针 = 注入的常量）⇒ **同一份格式化逻辑可被穷举断言**。
//
// ══════════════════════════════════════════════════════════════════════════════
// ★★ 秒级重绘门控（台账 §4 第 2 件）
// ══════════════════════════════════════════════════════════════════════════════
//
// > ★ **秒级重绘门控** —— 时钟只需**秒级**刷新，而主帧循环是 **15.625 ms 网格**
// > ⇒ 必须"仅当秒变化时重绘"。**不做这一步 = 每秒白烧 60 帧的整岛重绘**。
//
// ★ 判据就是 [ClockText.secondOf]：**它一变，才需要重绘**。
//   调用方（帧循环）只比较它的返回值，**不自己算时间**（同一条"唯一出口"纪律）。
//
// ══════════════════════════════════════════════════════════════════════════════

package dev.cdl.render

import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * ⑱ 时钟的**文本**与**重绘门控键** —— 全纯函数（时间由参数注入）。
 *
 * ## 小时制：**24 制 / 12 制可切**（用户 2026-10-03 明确要求）
 *
 * | 档 | 格式 | 例 |
 * |---|---|---|
 * | [HOUR_FORMAT_24]（默认） | `HH:mm`（补零） | `09:05` · `21:34` |
 * | [HOUR_FORMAT_12] | `h:mm`（**不补零**，`0` ⇒ `12`） | `9:05` · `9:34` |
 *
 * ### ★★ 为什么 12 制的 AM/PM **不能做成字母**（用真实常量算过）
 *
 * `SevenSegment` 的宽度模型：数字宽 = 1.0 · 冒号 = 0.35 · 字距 = 0.30。
 *
 * | 文本 | 逻辑宽 | 56 px 下的段厚 | 结论 |
 * |---|---|---|---|
 * | `09:05`（24 制） | 5.55 | **1.61 px** ✓ | 放得下 |
 * | `9:05`（12 制） | **4.25** | **2.11 px** ✓✓ | **更宽松** |
 * | `12:34P`（12 制 + 字母） | **6.85** | ★ **1.31 px** ✗ | **低于可读下限 1.5** ⇒ **放不下** |
 *
 * ⇒ ★ **AM/PM 不进文本**（[isPm] 单独返回），12 制的文本宽度**始终 ≤ 24 制** ⇒ 永远放得下 ✓
 *
 * ★★★ **2026-10-10 更正（审计 v4 · A-1）**：★ 上面那句原来接着写「**调用方在插槽里画一个小标记**」——
 * ★★ **那是假的**：**没有任何绘制代码**（`isPm` 只被 KDoc 与探针引用）✗
 * ★ 而"补绘制"这条路**实测是死的**：
 *   · 若 AM/PM 占第 6 个字形 ⇒ 比例 6.85 ⇒ 56 px 下段厚 **1.31 px < 可读下限 1.5** ⇒ 放不下；
 *   · ★★ **字形渲染器只支持 `0-9` 与 `:`**（`SevenSegment.maskOf` / `DotMatrix.maskOf`
 *     的 `else -> -1`）⇒ ★ **字母根本画不出来**（实测 `totalWidthRatio("PM") == 0`）；
 *   · 要画就得扩**三张**真值表，而**七段上 `M` 没有标准写法**。
 * ⇒ ★ **用户 2026-10-10 拍板：不显示上下午**，并把设置文案里的承诺**删掉**
 *   （见 `SettingRegistry` 的 `clock.hour_format`）✓
 * ⇒ ★ 故 [isPm] 现在是**"已备好但未接线"的数据**（见它的 KDoc）✓
 *
 * ★ 这与本项目"**把画不出来的东西在进入绘制之前挡掉**"是同一条纪律
 *   （`SevenSegment.fitDigitWidth` / `MaterialLayers.highlightPaint` 都返回 `null` 而不是硬画）。
 */
public object ClockText {

    /** 24 小时制（默认）—— `HH:mm`。 */
    public const val HOUR_FORMAT_24: String = "H24"

    /** 12 小时制 —— `h:mm`（不补零）。★ AM/PM 由 [isPm] 单独给出，**不进文本**。 */
    public const val HOUR_FORMAT_12: String = "H12"

    /**
     * ★★ **格式器缓存** —— 不是性能优化，是**正确性**要求。
     *
     * `DateTimeFormatter.ofPattern` 每次调用都**新建**一个不可变实例，
     * 而本函数**每帧都可能被调**。★ 更重要的理由：**时区 + 小时制**都编码在实例里
     *   ⇒ 换任一者都必须换实例 ⇒ 用 `(zone, pattern)` 当缓存键
     *   （`ConcurrentHashMap` 保证线程安全 —— 绘制在 EDT、探针可能在别的线程）。
     */
    private val formatters = java.util.concurrent.ConcurrentHashMap<String, DateTimeFormatter>()

    private fun formatterFor(zone: ZoneId, hourFormat: String): DateTimeFormatter {
        val pattern = if (hourFormat == HOUR_FORMAT_12) "h:mm" else "HH:mm"
        return formatters.computeIfAbsent("${zone.id}|$pattern") {
            DateTimeFormatter.ofPattern(pattern).withZone(zone)
        }
    }

    /**
     * ★★ **时钟文本**（`HH:mm` 或 `h:mm`）。
     *
     * ★ **`epochMs` 由调用方注入** —— 见文件头"为什么时间源必须可注入"。
     *   真机传 `System.currentTimeMillis()`；探针传常量。
     *
     * @param epochMs 自 Unix 纪元起的**毫秒**（可正可负，不特判）。
     * @param zone 时区（真机 = `ZoneId.systemDefault()`；探针可注入 ⇒ **可测跨时区**）。
     * @param hourFormat [HOUR_FORMAT_24]（默认）或 [HOUR_FORMAT_12]；**未知值按 24 制**。
     * @return 24 制恒 **5 字符**；12 制 **4–5 字符**（`h:mm` 或 `hh:mm`，取决于小时是否两位）。
     */
    public fun format(epochMs: Long, zone: ZoneId, hourFormat: String = HOUR_FORMAT_24): String =
        formatterFor(zone, hourFormat).format(Instant.ofEpochMilli(epochMs))

    /**
     * ★★ **12 制下的 AM/PM** —— `true` = 下午（PM）。
     *
     * ★ **为什么单独返回而不是并进文本**：见类 KDoc 的宽度表 —— 并进去就**放不下**。
     * ★ 24 制下本值**无意义**（调用方不应画标记）；这里仍如实返回（便于探针断言，
     *   也避免"调用方忘了判断小时制"时拿到一个假值）。
     *
     * ★★★ **2026-10-10（审计 v4 · A-1）：当前【没有生产调用点】—— 已备好、未接线** ✓
     *   ★ 原因：**上下午不显示**（用户 2026-10-10 拍板）——
     *     详见类 KDoc 的"更正"段：字形渲染器**不支持字母**，且第 6 个字形**放不下** ✓
     *   ★ 故本函数现在只被 `SevenSegmentProbe` 断言（**保留**：它是一条正确的纯函数契约，
     *     将来若扩了字形表 / 换了显示方案，直接接线即可）✓
     *   ⚠️ **不得**因为"没人调"就删掉它的断言 —— 那会把契约一起删掉 ✗
     *
     * 口径：**`0:00–11:59` ⇒ AM；`12:00–23:59` ⇒ PM**（与 12 制显示的 `12:xx` = 正午一致）。
     */
    public fun isPm(epochMs: Long, zone: ZoneId): Boolean {
        val hour = java.time.Instant.ofEpochMilli(epochMs).atZone(zone).hour
        return hour >= 12
    }

    /**
     * ★★★ **重绘门控键** —— 返回值**变了才需要重绘**。
     *
     * ## ★★ 口径（2026-10-03 二次修正）：**秒级**
     *
     * > 用户原话：「**HH：MM中间的冒号要能显示秒的跳动。这个怎么描述呢，就是一闪一闪的那种效果。**」
     *
     * | 轮次 | 口径 | 理由 |
     * |---|---|---|
     * | 台账原记 | **秒级** | —— |
     * | ★ 我第一版改成 **分钟级** | 分钟级 | "`HH:MM` 文本每分钟才变 ⇒ 秒级会多刷 60 倍" |
     * | ★★ **本版改回【秒级】** | **秒级** | ★ **冒号每秒闪一次** ⇒ 画面**每秒都变** ⇒ 我那条推理**只看了文本、漏了冒号** |
     *
     * ★ **判据（可复用的教训）**：**门控粒度 = "画面上会变的最细的那个东西"的粒度**，
     *   不是"文本的粒度"。★ 我当时把"文本每分钟变"当成了"画面每分钟变"。
     *
     * ## 语义
     *
     * 返回"该时刻所在的那个**秒**"的编号（自纪元起的**秒**）。
     * ★ 它**不是**"现在几秒"（`0..59`）—— 用**绝对秒编号**才能区分
     *   「12:34:56」与「12:35:56」，而后者**必须重绘**。
     *
     * @return 绝对秒编号；**同一秒内多次调用恒等**。
     */
    public fun secondOf(epochMs: Long): Long {
        // ★ 用 `floorDiv`（不是 `/`）：负数毫秒下 `/` **向零取整**
        //   ⇒ -1ms 与 +999ms 会落到同一秒 ⇒ 门控在纪元前**漏重绘**。
        return Math.floorDiv(epochMs, 1000L)
    }

    /**
     * ★★★ **冒号此刻是否可见** —— 经典电子钟的"一闪一闪"。
     *
     * ## ★★ 口径（2026-10-03 **二次修正**）：**半秒亮 / 半秒灭（1 Hz）**
     *
     * > 用户追问：「**这跳秒逻辑有问题吧？现实中常见的大众认知的是这样的吗？**」
     *
     * | 版本 | 半周期 | 频率 | 对不对 |
     * |---|---|---|---|
     * | 我第一版 | **1000 ms** | **0.5 Hz**（2 秒一个周期） | ✗ **错** |
     * | ★★ **本版** | **500 ms** | ★ **1 Hz**（**1 秒一个周期**） | ✓ **大众认知** |
     *
     * ★★ **为什么 1 Hz 才对**：用户的原话是「**冒号要能显示秒的跳动**」——
     *   ⇒ 冒号是**秒的指示器** ⇒ **一个"亮-灭"周期 = 一秒** ⇒ 用户能**跟着数秒**。
     *   我第一版 2 秒一个周期 ⇒ 看着像"有个东西在闪"，**数不出秒** ✗
     *
     * ★★ **我当时的错误理由**（留档，防再犯）：我写「半秒闪在 15.625 ms 的帧网格上**看起来太急**」
     *   —— ★ 那是**拿个人偏好去改通用约定**。**电子钟/微波炉/手机时钟一律 1 Hz**，
     *     用户的心智模型就是它；"急不急"不是我能替用户定的。
     *
     * ## 语义
     *
     * ```
     * 可见  ⇔  floorDiv(epochMs, 500) 是偶数
     * ```
     * ★ **相位以"绝对半秒编号"的奇偶为准** ⇒ 同一时刻在任何机器上**相位一致**，
     *   且**无需存状态**（可复现）。⇒ 亮灭翻转**恰好落在整秒与半秒边界** ✓
     *
     * @return `true` = 本半秒**画**冒号；`false` = **不画**（但**仍占位**，见 [SevenSegment.textPolygons]）。
     */
    public fun colonVisible(epochMs: Long): Boolean = repaintTickOf(epochMs) % 2L == 0L

    /**
     * ★★ **重绘节拍编号**（半秒一格）—— 门控键。
     *
     * ★ 取 **500 ms**（不是 1000）—— 因为冒号是 **1 Hz**（半秒翻一次）⇒
     *   **画面上最细的变化是半秒** ⇒ 门控必须比它更细或相等 ⇒ **半秒**。
     * ★★ 这正是"**门控粒度 = 画面上会变的最细的那个东西的粒度**"那条判据
     *   （我在 ③ 里已经栽过一次：把"文本每分钟变"当成"画面每分钟变"）。
     */
    public fun repaintTickOf(epochMs: Long): Long {
        // ★ 用 `floorDiv`（不是 `/`）：负数毫秒下 `/` **向零取整**
        //   ⇒ -1ms 与 +499ms 会落到同一格 ⇒ 门控在纪元前**漏重绘**。
        return Math.floorDiv(epochMs, 500L)
    }

    /**
     * ★★ **要不要重绘** —— 判据只有一条：**节拍编号变了**（半秒一格）。
     *
     * ★ 这一条**同时**服务三个变化源：
     *   · **冒号**的亮灭（**每 500 ms**）
     *   · **文本**的变化（每分钟；跨小时/跨日也在此内）
     *   ⇒ 取**较细的那个**（500 ms）✓
     *
     * @param prevTick 上一次绘制时的 [repaintTickOf] 值。
     * @param nowTick 本帧的 [repaintTickOf] 值。
     * @return `true` ⇒ **需要重绘**。
     */
    public fun shouldRepaint(prevTick: Long, nowTick: Long): Boolean = prevTick != nowTick
}
